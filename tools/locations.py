#!/usr/bin/env python3
"""Build names/item_locations.txt: the ItemLotParam_map rows and ShopLineupParam slots that are real
item locations in the world.  --random-flask-locations draws the new places of the two flasks from it.

A regulation.bin does not say which lot rows a map, an enemy or an event script actually references,
and ItemLotParam_map keeps cut-content rows next to the real ones (Sword of Light +1..+10 template
rows, Spectral Steed Attire, empty 1043310xxx rows).  The Item and Enemy Randomizer knows the real
ones (it reads the map files) and rewrites exactly those, so the list is the set of rows whose item
differs between a vanilla regulation.bin and one the item randomizer wrote, restricted to:

ItemLotParam_map
    10000-99999        boss, field boss, evergaol and teardrop scarab rewards (awarded by events)
    100000-999999      NPC gifts and NPC corpse drops of the Lands Between (quest-dependent, the user
                       accepts that); those of the Land of Shadow are left out, its NPC quests break
                       too easily
    10000000+          pickups in legacy dungeons, catacombs, caves, tunnels and towers (8 digits),
                       troll carriage chests (9xxxxxxxx), the overworld (10xxxxxxxx = m60) and the
                       Land of Shadow (20xxxxxxxx = m61)
    left out           < 10000 (starting gear, the flasks, quest-only rewards), 1000000-9999999 (unused)
ShopLineupParam
    slots whose item (equipId / equipType) the item randomizer changed: merchants, Twin Maiden Husks,
    Enia's remembrance forging, Dragon Communion...; the shops of the Land of Shadow (ids 102250+: Moore,
    Thiollier, Ymir's sorceries, Bayle's altar) are left out, all of them belong to quest NPCs; rows
    where only a flag or the price changed (the remembrance duplication menus) are not locations

Each line: table, row id, "base" or "dlc", the row's vanilla content as named in names/<table>.txt.
dlc = the Land of Shadow (ids 20xxxxxxxx), its legacy and minor dungeons (8-digit ids whose map area
is 20-29 or 40-49) and the rows Paramdex names without a [location] prefix (for game 1.17.1 every
such 5- / 6-digit row is DLC: Paramdex added those names without the prefix).

Usage (run once per game version, from the project directory, with the game's Oodle DLL present):
    python tools/locations.py regulation_vanilla.bin regulation_item_randomized.bin
    python tools/locations.py VANILLA RANDOMIZED -o some/other/file.txt
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import erreg  # noqa: E402

HERE = Path(__file__).resolve().parent
LOCATIONS_FILE = HERE / "names" / "item_locations.txt"
SLOT_FIELDS = ("lotItemId", "lotItemCategory", "lotItemNum", "lotItemBasePoint")


def lot_content(P: erreg.Param, r) -> tuple:
    return tuple(P.get(r, f"{f}0{i}") for i in range(1, 9) for f in SLOT_FIELDS)


def shop_content(P: erreg.Param, r) -> tuple:
    return P.get(r, "equipId"), P.get(r, "equipType")


def lot_wanted(rid: int) -> bool:
    return 10000 <= rid < 1_000_000 or rid >= 10_000_000


def lot_dlc(rid: int, name: str) -> bool:
    if rid < 1_000_000:
        return not name.startswith("[")
    if rid < 100_000_000:
        area = rid // 1_000_000
        return 20 <= area < 30 or 40 <= area < 50
    return rid >= 2_000_000_000


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("vanilla", help="unmodified regulation.bin of the game version")
    ap.add_argument("randomized", help="regulation.bin written by the Item and Enemy Randomizer (DLC included)")
    ap.add_argument("-o", "--output", default=str(LOCATIONS_FILE))
    args = ap.parse_args(argv)
    V, R = erreg.Regulation(args.vanilla), erreg.Regulation(args.randomized)
    lines = ["# Real item locations: ItemLotParam_map rows and ShopLineupParam slots the Item and Enemy Randomizer",
             "# rewrote (table, id, base|dlc, vanilla content).  Generated by tools/locations.py, see its docstring.",
             f"# vanilla: {Path(args.vanilla).name}  item-randomized: {Path(args.randomized).name}"]
    n = {"lots": 0, "npc": 0, "shops": 0, "dlc": 0}

    pd = erreg.load_paramdef(HERE / "paramdef" / "ItemLotParam.xml")
    names = erreg.load_names(HERE / "names" / "ItemLotParam_map.txt")
    VL, RL = V.param("ItemLotParam_map", pd), R.param("ItemLotParam_map", pd)
    for r in VL.rows:
        q = RL.by_id.get(r.id)
        if q is None or not lot_wanted(r.id) or lot_content(VL, r) == lot_content(RL, q):
            continue
        name = names.get(r.id, "")
        dlc = lot_dlc(r.id, name)
        npc = 100_000 <= r.id < 1_000_000
        if npc and dlc:
            continue
        n["npc" if npc else "lots"] += 1
        n["dlc"] += dlc
        lines.append(f"ItemLotParam_map\t{r.id}\t{'dlc' if dlc else 'base'}\t{name}".rstrip())

    pd = erreg.load_paramdef(HERE / "paramdef" / "ShopLineupParam.xml")
    names = erreg.load_names(HERE / "names" / "ShopLineupParam.txt")
    VS, RS = V.param("ShopLineupParam", pd), R.param("ShopLineupParam", pd)
    for r in VS.rows:
        q = RS.by_id.get(r.id)
        name = names.get(r.id, "")
        if q is None or shop_content(VS, r) == shop_content(RS, q) or not name.startswith("[") or r.id >= 102000:
            continue
        n["shops"] += 1
        lines.append(f"ShopLineupParam\t{r.id}\tbase\t{name}".rstrip())
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.output}: {n['lots']} pickups / rewards ({n['dlc']} of them Land of Shadow), "
          f"{n['npc']} NPC gifts / corpses, {n['shops']} shop slots")
    return 0


if __name__ == "__main__":
    sys.exit(main())
