#!/usr/bin/env python3
"""Build names/ItemLotParam_map.locations.txt: the ItemLotParam_map rows that are real item locations
in the world.  --random-flask-locations draws the new places of the two flasks from it.

A regulation.bin does not say which lot rows a map, an enemy or an event script actually references,
and ItemLotParam_map keeps cut-content rows next to the real ones.  The Item and Enemy Randomizer
knows the real ones (it reads the map files) and rewrites exactly those rows, so the list is the set
of rows whose contents differ between a vanilla regulation.bin and one the item randomizer wrote,
restricted to pickups and boss / scarab rewards:

    ids 10000-99999      boss, field boss, evergaol and teardrop scarab rewards (awarded by events)
    ids 10000000+        pickups in legacy dungeons, catacombs, caves, tunnels and towers (8 digits),
                         troll carriage chests (9xxxxxxxx), the overworld (10xxxxxxxx = m60) and
                         the Land of Shadow (20xxxxxxxx = m61)
    left out            < 10000 (starting gear, the flasks, quest-only rewards), 100000-999999 (NPC
                         gifts and NPC corpse drops: quest-dependent), 1000000-9999999 (unused)

Each line: lot id, "base" or "dlc", the row's vanilla content as named in names/ItemLotParam_map.txt.
dlc = the Land of Shadow (ids 20xxxxxxxx), its legacy and minor dungeons (8-digit ids whose map area
is 20-29 or 40-49) and the boss / scarab rewards Paramdex names without a [location] prefix (for game
1.17.1 every one of those is a DLC boss; the base-game rewards all carry a prefix).

Usage (run once per game version, from the project directory, with the game's Oodle DLL present):
    python tools/lotdiff.py regulation_vanilla.bin regulation_item_randomized.bin
    python tools/lotdiff.py VANILLA RANDOMIZED -o some/other/file.txt
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import erreg  # noqa: E402

HERE = Path(__file__).resolve().parent
LOCATIONS_FILE = HERE / "names" / "ItemLotParam_map.locations.txt"
SLOT_FIELDS = ("lotItemId", "lotItemCategory", "lotItemNum", "lotItemBasePoint")


def content(P: erreg.Param, r) -> tuple:
    return tuple(P.get(r, f"{f}0{i}") for i in range(1, 9) for f in SLOT_FIELDS)


def wanted(rid: int) -> bool:
    return 10000 <= rid < 100000 or rid >= 10_000_000


def is_dlc(rid: int, name: str) -> bool:
    if rid < 100000:
        return not name.startswith("[")
    if rid < 100_000_000:
        area = rid // 1_000_000
        return 20 <= area < 30 or 40 <= area < 50
    return rid >= 2_000_000_000


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("vanilla", help="unmodified regulation.bin of the game version")
    ap.add_argument("randomized", help="regulation.bin written by the Item and Enemy Randomizer (DLC included)")
    ap.add_argument("-o", "--output", default=str(LOCATIONS_FILE))
    args = ap.parse_args(argv)
    pd = erreg.load_paramdef(HERE / "paramdef" / "ItemLotParam.xml")
    names = erreg.load_names(HERE / "names" / "ItemLotParam_map.txt")
    V = erreg.Regulation(args.vanilla).param("ItemLotParam_map", pd)
    R = erreg.Regulation(args.randomized).param("ItemLotParam_map", pd)
    lines = ["# ItemLotParam_map rows that are real item locations: rows the Item and Enemy Randomizer rewrote",
             "# (lot id, base|dlc, vanilla content).  Generated by tools/lotdiff.py, see its docstring.",
             f"# vanilla: {Path(args.vanilla).name}  item-randomized: {Path(args.randomized).name}"]
    n = {"base": 0, "dlc": 0}
    for r in V.rows:
        q = R.by_id.get(r.id)
        if q is None or not wanted(r.id) or content(V, r) == content(R, q):
            continue
        name = names.get(r.id, "")
        tag = "dlc" if is_dlc(r.id, name) else "base"
        n[tag] += 1
        lines.append(f"{r.id}\t{tag}\t{name}".rstrip())
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.output}: {n['base']} base + {n['dlc']} dlc rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
